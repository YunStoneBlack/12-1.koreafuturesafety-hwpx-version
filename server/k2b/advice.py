"""K2B 제출 실패를 사람이 바로 할 일로 바꾼 한 줄(2026-10-02 사용자: "실패 안내 다듬기").

runner가 남기는 실패 문구(message)는 원인 그대로라 길거나(K2B 창 문구) 영어(Playwright 시간 초과)일 수 있다 — 문구 모양과
마지막으로 하던 단계(log 끝 줄)를 보고 "이렇게 하세요"를 고른다. 제출 창·현장 화면 보고서 줄·보고서 화면이 같이 쓴다.
"""
from __future__ import annotations

import re

# (문구에 이게 있으면, 이렇게 하세요) — 위에서부터 처음 맞는 것
_BY_MESSAGE: list[tuple[str, str]] = [
    (r"차수는 .*회차라 저장하지 않았습니다",
     "K2B에 이 회차가 이미 올라가 있거나 회차 번호가 어긋났습니다. K2B 차수 목록을 먼저 보고, 맞게 올리는 거라면 "
     "[차수가 달라도 저장하고 다시 제출]을 누르세요."),
    (r"해당없음.*낼 수 없습니다|통보여부를 선택",
     "이전 기술지도 이행여부를 '이행' 또는 '불이행'으로 고르고 다시 제출하세요('해당없음'은 K2B 1차수에서만 됩니다)."),
    (r"비계사용현황", "제출 창에서 비계 사용(사용/미사용)을 고르고 다시 제출하세요."),
    (r"대형사고 위험작업", "제출 창의 대형사고 위험작업 줄을 확인하세요(없으면 줄을 모두 빼면 '해당없음'으로 올라갑니다)."),
    (r"정상적으로 저장되었습니다' 창을 못 봤습니다",
     "저장됐는지 확실하지 않습니다. K2B 차수 목록에 이 회차가 있는지 먼저 보고, 없을 때만 다시 제출하세요(두 번 올라갈 수 있음)."),
    (r"일치하는 현장을 찾지 못했습니다",
     "K2B에 등록된 현장 이름과 웹 현장 이름이 다릅니다. 현장 정보 [수정]에서 현장명을 K2B와 똑같이 맞추고 다시 제출하세요."),
    (r"일치하는 행이 \d+개",
     "K2B에 같은 이름의 현장이 여러 개라 고를 수 없습니다. 이 회차는 K2B에서 직접 올리고 관리자에게 알려 주세요."),
    (r"수정가능 기한|7일",
     "기술지도일로부터 7일이 지나 K2B에서 보고서를 고칠 수 없습니다. 지도일이 맞는지 확인하세요."),
    (r"K2B 계정이 없습니다", "담당요원 탭에서 이 요원의 K2B 아이디·비밀번호를 등록하고 [로그인 확인]을 누르세요."),
    (r"K2B가 저장을 막았습니다 — (.+)",
     "K2B가 '{0}'라며 저장을 막았습니다. 그 칸을 보고서나 제출 창에서 채운 뒤 다시 제출하세요."),
]

# 시간 초과 등 문구로 알 수 없을 때 — 마지막으로 하던 단계로
_BY_STEP: list[tuple[str, str]] = [
    (r"로그인|기술지도 화면으로 이동",
     "K2B 로그인이 안 됐을 수 있습니다. 담당요원 탭에서 [로그인 확인]을 눌러 보고(비밀번호가 바뀌었으면 다시 등록), 다시 제출하세요."),
    (r"첨부", "K2B가 사진·파일을 받는 데 오래 걸렸습니다. 잠시 뒤 다시 제출하세요."),
]

_FALLBACK = "K2B 화면이 늦게 뜨거나 바뀌어서 멈췄습니다. 잠시 뒤 다시 제출해 보고, 또 실패하면 K2B 화면 사진과 함께 알려 주세요."


def advice(message: str, log: str = "") -> str:
    """실패 문구(+ 단계 기록) → 이렇게 하세요 한 줄."""
    message = message or ""
    for pattern, text in _BY_MESSAGE:
        m = re.search(pattern, message)
        if m:
            return text.format(*(g.strip().rstrip(".") for g in m.groups()))
    steps = [line for line in (log or "").splitlines() if "실패:" not in line]
    last = steps[-1] if steps else ""
    for pattern, text in _BY_STEP:
        if re.search(pattern, last):
            return text
    return _FALLBACK
