def same_item(no: int, name: str) -> bool:
    """회사 원본 항목(번호·이름)이 매뉴얼 그 번호 항목인지 — 띄어쓰기·괄호 빼고 비슷하면."""
    import difflib
    import re

    if no not in NAMES:
        return False
    bare = lambda t: re.sub(r"[\s()·,]", "", t)  # noqa: E731
    return difflib.SequenceMatcher(None, bare(NAMES[no]), bare(name)).ratio() >= 0.7


def criteria(items: list[dict]) -> str:
    """AI 초안에 넣을 18항목 줄 — "번호. [영역] 이름 (지난 평가)" 아래 그 항목 a~e 기준(매뉴얼 항목과 이름이 안 맞는 번호는 이름만)."""
    lines = []
    for it in items:
        lines.append(f"{it['no']}. [{it['group']}] {it['name']} (지난 {it['rating'] or '-'})")
        c = BUILDING.get(it["no"]) if same_item(it["no"], it["name"]) else None
        if c:
            lines.extend(f"   {g}({GRADE_WORD[g]}) {c[g]}" for g in "abcde")
            if it["no"] in PARTIAL:
                lines.append("   ※ 마감재 등으로 일부 구역만 조사되어 대표성이 없으면 a·b 불가(표 2-6 상태로, 조사 부위·불가 사유 명시)")
    return RULES + "\n\n" + "\n".join(lines)
