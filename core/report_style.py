"""AI가 쓰는 보고서 글 말투 한 곳(2026-10-23 형 "AI 분석 시 '사진상으로는'처럼 제3자가 판단한 것 같은 용어 빼기 — AI 분석 전체 적용").
시특법·옹벽·정밀·내진(server/sitok/vision.ask(writing=True)) + 산안법(core/vision_analyzer 지적사항·유해위험요인)이 같이 씀:
WRITING_STYLE = 프롬프트에 붙이는 규칙, clean_text = 그래도 나온 제3자 표현을 지우거나 점검자 말투로."""
from __future__ import annotations

import re

WRITING_STYLE = """[보고서 문장 말투 — 꼭 지킬 것]
이 글은 점검자가 현장에서 직접 조사하고 쓰는 안전점검 보고서 문장입니다. 사진을 받았더라도 "사진상으로는", "사진으로 보아", "사진에서 보이는",
"사진에서 확인된", "~로 보인다", "~것으로 보임"처럼 제3자가 사진을 보고 판단한 듯한 표현은 쓰지 말고, "~조사되었다", "~확인되었다",
"~판단된다"처럼 점검자가 직접 확인한 문장으로 쓰세요. 판단이 어려운 것은 "확인 곤란"처럼 짧게.
"사진자료로 확인하였으며"처럼 자료를 남이 검토한 듯한 말, 사진 칸 이름·파일 이름(heavy_1, front.jpg 등)·"사진 2장" 같은 자료 출처는 쓰지 말고 조사한 내용만 쓰세요.
받은 자료(입력값·사진·점검자가 덧붙인 내용)에 없는 수치·부재·위치·결함은 지어내지 말고, 쓸 내용이 없으면 비워 두세요(10/28 사용자 — 내진에서 시특법·산안법까지)."""
# 그래도 나온 제3자 표현 지우기(10/23 형 "AI 분석 시 '사진상으로는'처럼 제3자가 판단한 것 같은 용어 빼기 — AI 분석 전체 적용")
_THIRD = [
    (re.compile(r"(?:촬영된\s?)?사진\s?상(?:으로(?:는|도)?|에서(?:는)?)?(?=[\s,.]|$)\s*,?\s*"), ""),  # "사진상으로는," — "사진 상단"은 안 건드림
    (re.compile(r"(?:촬영된\s?)?사진(?:으로|에서)\s?(?:보면|보아|볼\s?때|판단(?:하면|할\s?때|하건대)|확인(?:한|된|되는)\s?(?:결과|바)(?:로는|와\s?같이|에\s?의하면)?)\s*,?\s*"), ""),
    (re.compile(r"(?:촬영된\s?)?사진(?:에서|상)\s?(?:보이는|확인되는|관찰되는|나타난)\s?"), ""),
    (re.compile(r"것으로\s?보(?:인다|여진다)"), "것으로 판단된다"),
    (re.compile(r"것으로\s?보임"), "것으로 판단됨"),
    (re.compile(r"것으로\s?보이며"), "것으로 판단되며"),
    (re.compile(r"것으로\s?보이(?:고|나)"), "것으로 판단되고"),
    (re.compile(r"\s*\((?:[a-z]+_\d+(?:\.\w+)?(?:,\s*)?)+\)"), ""),  # 사진 칸 이름 "(heavy_1, heavy_2)"(10/28 내진 — 제3자처럼 자료 출처를 적던 것)
    (re.compile(r"사진\s?자료\s?(?:를\s?통해|로|으로)\s?"), ""),  # "사진자료로 확인하였으며" → "확인하였으며"
]


def rewrite_prompt(label: str, current: str, note: str, context: str = "") -> str:
    """AI가 쓴 글 한 칸을 점검자가 덧붙인 내용을 반영해 다시 쓰는 질문(10/28 사용자 "내진의 반영해 다시 쓰기를 시특법·산안법에도") — 말투는 WRITING_STYLE(system)."""
    return (f"아래는 안전점검 보고서의 글 칸 '{label}'의 지금 글과 점검자가 덧붙인 내용입니다. 지금 글을 바탕으로 덧붙인 내용을 반드시 반영해 같은 형식(줄 수·글머리·길이 비슷하게)으로 다시 써 주세요. "
            "지금 글과 덧붙인 내용에 없는 수치·부재·위치·결함은 지어내지 말고, 덧붙인 내용이 지금 글과 다르면 덧붙인 내용을 따르세요. 머리말·설명 없이 고쳐 쓴 글만 주세요."
            + (f"\n\n[보고서]\n{context}" if context else "")
            + f"\n\n[지금 글]\n{current or '(비어 있음)'}\n\n[점검자가 덧붙인 내용 — 반드시 반영]\n{note or '(없음 — 말투·문장만 다듬기)'}")


def clean_text(s: str) -> str:
    """보고서 글에서 제3자 표현("사진상으로는"·"사진에서 보이는"·"~것으로 보인다")을 빼거나 점검자 말투로. 지운 뒤 겹친 빈칸 정리."""
    if not s:
        return s
    for pat, rep in _THIRD:
        s = pat.sub(rep, s)
    s = re.sub(r"[ \t]{2,}", " ", s)
    s = re.sub(r"([(\[\"'“‘])\s+", r"\1", s)
    s = re.sub(r"\s+([,.)\]])", r"\1", s)
    return s
